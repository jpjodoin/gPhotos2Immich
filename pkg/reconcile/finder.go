package reconcile

import (
	"context"
	"strings"
	"time"

	"warreth.dev/gphotos2immich/pkg/immich"
	"warreth.dev/gphotos2immich/pkg/match"
)

// DefaultMaxWideCandidates bounds the fallback timestamp window. On a busy day
// the wide window can return hundreds of assets, and comparing all of them is
// not worth it: we prefer keeping a duplicate over burning through requests.
const DefaultMaxWideCandidates = 25

// CandidateClient is the Immich capability needed to find candidates.
type CandidateClient interface {
	SearchMetadata(ctx context.Context, filter immich.SearchFilter) ([]immich.Asset, error)
}

// IsOwnUpload reports whether a filename was generated by this tool. Those
// copies must never win a match against a real user asset.
func IsOwnUpload(name string) bool {
	return strings.HasPrefix(name, "gp_")
}

// FindCandidates returns plausible Immich assets for a fingerprint: first in a
// tight timestamp window, then in a wider one when nothing is found.
func FindCandidates(ctx context.Context, client CandidateClient, fp match.Fingerprint, narrow, wide time.Duration) []match.Candidate {
	if fp.TakenAt.IsZero() {
		return nil
	}

	candidates := searchCandidates(ctx, client, fp.TakenAt.Add(-narrow), fp.TakenAt.Add(narrow), 50)
	if len(candidates) > 0 {
		return candidates
	}
	if wide <= 0 {
		return nil
	}

	candidates = searchCandidates(ctx, client, fp.TakenAt.Add(-wide), fp.TakenAt.Add(wide), 100)
	if len(candidates) > DefaultMaxWideCandidates {
		return nil
	}
	return candidates
}

func searchCandidates(ctx context.Context, client CandidateClient, from, to time.Time, limit int) []match.Candidate {
	assets, err := client.SearchMetadata(ctx, immich.SearchFilter{
		TakenAfter:  from,
		TakenBefore: to,
		Size:        limit,
	})
	if err != nil {
		return nil
	}

	candidates := make([]match.Candidate, 0, len(assets))
	for _, asset := range assets {
		if asset.IsTrashed || asset.Visibility == "hidden" || IsOwnUpload(asset.OriginalFileName) {
			continue
		}
		candidates = append(candidates, ToCandidate(asset))
	}
	return candidates
}

// ToCandidate converts an Immich asset into a matcher candidate.
func ToCandidate(asset immich.Asset) match.Candidate {
	return match.Candidate{
		ID:       asset.ID,
		FileName: asset.OriginalFileName,
		Width:    asset.Width,
		Height:   asset.Height,
		IsVideo:  asset.IsVideo(),
		TakenAt:  asset.FileCreatedAt,
	}
}
